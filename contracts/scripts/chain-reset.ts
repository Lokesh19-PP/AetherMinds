/**
 * contracts/scripts/chain-reset.ts
 * Demo tamper simulation: "chain-reset" scenario from section 20.9.
 *
 * What it simulates:
 *   The local Hardhat node is restarted (erasing all in-memory state),
 *   then a new RootAnchor contract is deployed at a different address.
 *   A new batch is sealed on the fresh chain only.  The old ledger anchor
 *   still holds the original root, but the Ethereum anchor is now gone.
 *
 *   When the verifier then checks a proof bundle that references the OLD
 *   chain anchor id, it will get ROOT_NOT_FOUND from Ethereum (the new
 *   contract has no entries), while the ledger passes — triggering an
 *   ANCHOR_DISAGREEMENT.
 *
 * Usage (from workspace root):
 *   npm run demo:tamper -- chain-reset
 *   # which calls: cd contracts && npx hardhat run scripts/chain-reset.ts --network localhost
 *
 * Alternatively, trigger directly:
 *   cd contracts && npx hardhat run scripts/chain-reset.ts --network localhost
 *
 * NOTE: This script requires the Hardhat node to already be running on :8545.
 *       It intentionally does NOT restart the node process — instead it
 *       deploys a second fresh contract to the same running node, simulating
 *       the loss of old state (since a real node restart clears in-memory
 *       state anyway, and that is best triggered by the operator manually).
 *
 * For the demo:
 *   1. Run `npm run chain` to start Hardhat node.
 *   2. Run `npm run chain:deploy` to deploy RootAnchor and seed batches.
 *   3. Verify a document — should show ✅ OK (two anchors).
 *   4. Run this script (chain-reset) — deploys a NEW contract.
 *   5. Verify the same document again — should show ❌ ANCHOR_DISAGREEMENT
 *      because the ledger still holds the root but the NEW Ethereum contract
 *      has no entries, so ethereum anchor shows ROOT_NOT_FOUND.
 *
 * Say to judges: "We run the chain ourselves, so we can reset it. The
 * verifier notices because the ledger and the chain no longer agree. On
 * a public chain no one could reset it."
 */

import { ethers, network } from 'hardhat';
import * as fs from 'fs';
import * as path from 'path';

const WORKSPACE_ROOT = path.resolve(__dirname, '..', '..');
const ENV_FILE = path.join(WORKSPACE_ROOT, '.env');
const PINNED_FILE = path.join(
  WORKSPACE_ROOT,
  'apps', 'web', 'src', 'generated', 'pinnedEthereum.ts',
);

function upsertEnvVar(envPath: string, key: string, value: string): void {
  let content = '';
  if (fs.existsSync(envPath)) {
    content = fs.readFileSync(envPath, 'utf-8');
  }
  const lines = content.split('\n');
  const idx = lines.findIndex((l) => l.startsWith(`${key}=`));
  if (idx >= 0) {
    lines[idx] = `${key}=${value}`;
  } else {
    lines.push(`${key}=${value}`);
  }
  fs.writeFileSync(envPath, lines.join('\n'), 'utf-8');
}

async function main(): Promise<void> {
  const networkName = network.name;
  const { chainId } = await ethers.provider.getNetwork();
  const rpcUrl =
    networkName === 'localhost'
      ? 'http://127.0.0.1:8545'
      : (network.config as { url?: string }).url ?? 'http://127.0.0.1:8545';

  console.log('\n🎭 DEMO TAMPER: chain-reset simulation');
  console.log(`   Network: ${networkName} (chainId=${chainId})`);
  console.log('   Deploying a FRESH RootAnchor contract...');
  console.log('   (This simulates the chain having been reset/restarted)');
  console.log('');

  // Deploy a fresh contract with a new publisher wallet
  const freshPublisher = ethers.Wallet.createRandom().connect(ethers.provider);

  // Fund from dev account
  const [devAccount] = await ethers.getSigners();
  if (!devAccount) throw new Error('No signers. Is the Hardhat node running?');

  await (
    await devAccount.sendTransaction({
      to: freshPublisher.address,
      value: ethers.parseEther('0.5'),
    })
  ).wait();

  const Factory = await ethers.getContractFactory('RootAnchor', freshPublisher);
  const freshContract = await Factory.deploy(freshPublisher.address);
  await freshContract.waitForDeployment();
  const freshAddress = await freshContract.getAddress();

  console.log(`✅ Fresh RootAnchor deployed at: ${freshAddress}`);
  console.log(`   Entry count (should be 0): ${await freshContract.count()}`);
  console.log('');

  // Update pinnedEthereum.ts to point at the NEW (empty) contract
  // This means the verifier will now query the new contract for old anchor ids
  // → ROOT_NOT_FOUND for any previously anchored batch → ANCHOR_DISAGREEMENT
  const pinnedContent = `// AUTO-GENERATED by contracts/scripts/chain-reset.ts
// ⚠️  TAMPER SIMULATION ACTIVE — chain has been "reset"
// The verifier will detect ANCHOR_DISAGREEMENT for previously anchored batches.

export const pinnedEthereum = {
  chainId: ${chainId},
  contract: '${freshAddress}',
  rpcUrls: ['${rpcUrl}'],
  blockTag: 'latest',
} as const;

export type PinnedEthereum = typeof pinnedEthereum;
`;

  if (fs.existsSync(path.dirname(PINNED_FILE))) {
    fs.writeFileSync(PINNED_FILE, pinnedContent, 'utf-8');
    console.log(`📌 pinnedEthereum.ts updated to point at fresh contract.`);
  } else {
    console.log(`⚠️  apps/web/src/generated/ not found. pinnedEthereum.ts not updated.`);
    console.log(`   (Run 'npm run chain:deploy' first to create the directory.)`);
  }

  upsertEnvVar(ENV_FILE, 'ETH_CONTRACT', freshAddress);
  upsertEnvVar(ENV_FILE, 'CHAIN_PUBLISHER_KEY', freshPublisher.privateKey);

  console.log('');
  console.log('═'.repeat(60));
  console.log('🎭 Chain-reset simulation complete!');
  console.log('');
  console.log('What happened:');
  console.log('  • A NEW empty RootAnchor was deployed.');
  console.log('  • pinnedEthereum.ts now points at the new (empty) contract.');
  console.log('  • The ledger anchor still holds the original roots.');
  console.log('');
  console.log('Expected verifier result for any previously anchored proof:');
  console.log('  ❌ ANCHOR_DISAGREEMENT');
  console.log('     Ledger: passes (original root still there)');
  console.log('     Ethereum: ROOT_NOT_FOUND (new contract has no entries)');
  console.log('');
  console.log('Tell the judges:');
  console.log('  "We run the chain ourselves, so we can reset it. The verifier');
  console.log('   notices because the ledger and chain no longer agree. On a');
  console.log('   public network no single party can reset it."');
  console.log('═'.repeat(60));
  console.log('');
}

main().catch((err) => {
  console.error('chain-reset failed:', err);
  process.exit(1);
});
