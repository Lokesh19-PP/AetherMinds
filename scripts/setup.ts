import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { ed25519 } from '@noble/curves/ed25519';
import { bytesToHex, hexToBytes } from '@proofchain/core';

async function main() {
  console.log('🚀 Running ProofChain System Setup...');

  const rootDir = process.cwd();
  const anchorDataDir = path.join(rootDir, 'anchor-data');
  const witnessDataDir = path.join(rootDir, 'witness-data');
  const dataDir = path.join(rootDir, 'data');

  fs.mkdirSync(anchorDataDir, { recursive: true });
  fs.mkdirSync(witnessDataDir, { recursive: true });
  fs.mkdirSync(dataDir, { recursive: true });

  // 1. Generate or read Anchor Ed25519 Key
  const anchorKeyFile = path.join(anchorDataDir, 'anchor.key');
  let privSeed: Uint8Array;
  if (fs.existsSync(anchorKeyFile)) {
    const raw = fs.readFileSync(anchorKeyFile, 'utf8').trim();
    privSeed = hexToBytes(raw);
    console.log('   Using existing anchor private key.');
  } else {
    privSeed = new Uint8Array(crypto.randomBytes(32));
    const privHex = bytesToHex(privSeed);
    fs.writeFileSync(anchorKeyFile, privHex, { mode: 0o600 });
    console.log('   Generated fresh anchor Ed25519 private key.');
  }

  const pubBytes = ed25519.getPublicKey(privSeed);
  const anchorPubKey = bytesToHex(pubBytes);
  console.log(`   Anchor Public Key: ${anchorPubKey}`);

  // 2. Generate random tokens
  const anchorPublishToken = crypto.randomBytes(24).toString('hex');
  const registryApiToken = crypto.randomBytes(24).toString('hex');

  // 3. Write apps/web/src/generated/anchorPub.ts
  const webGenDir = path.join(rootDir, 'apps', 'web', 'src', 'generated');
  fs.mkdirSync(webGenDir, { recursive: true });
  const anchorPubTsPath = path.join(webGenDir, 'anchorPub.ts');
  const anchorPubContent = `// Auto-generated by scripts/setup.ts
// Pinned Anchor Ledger Ed25519 Public Key
export const PINNED_ANCHOR_PUBLIC_KEY = '${anchorPubKey}';
`;
  fs.writeFileSync(anchorPubTsPath, anchorPubContent, 'utf8');
  console.log(`   Wrote pinned public key to ${anchorPubTsPath}`);

  // 4. Create .env if not exists, or update key fields
  const envPath = path.join(rootDir, '.env');
  let envContent = '';
  if (fs.existsSync(envPath)) {
    envContent = fs.readFileSync(envPath, 'utf8');
  }

  const envVars: Record<string, string> = {
    REGISTRY_PORT: '4000',
    ANCHOR_PORT: '4100',
    WITNESS_PORT: '4200',
    WEB_ORIGIN: 'http://localhost:5173',
    ANCHOR_URL: 'http://localhost:4100',
    WITNESS_URL: 'http://localhost:4200',
    ANCHOR_PUBLISH_TOKEN: anchorPublishToken,
    REGISTRY_API_TOKEN: registryApiToken,
    ANCHOR_PUBLIC_KEY: anchorPubKey,
    PINNED_ANCHOR_PUBLIC_KEY: anchorPubKey,
    DATA_DIR: './data',
    ANCHOR_DATA_DIR: './anchor-data',
    WITNESS_DATA_DIR: './witness-data',
    DEMO_MODE: 'true',
    ANCHOR_MODE: 'both',
    ETH_RPC_URL: 'http://127.0.0.1:8545',
    ETH_CHAIN_ID: '31337',
  };

  const lines = envContent.split('\n').filter((l) => l.trim().length > 0);
  const existingKeys = new Set<string>();
  const newLines: string[] = [];

  for (const line of lines) {
    const match = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (match) {
      existingKeys.add(match[1]);
      if (match[1] === 'ANCHOR_PUBLIC_KEY' || match[1] === 'PINNED_ANCHOR_PUBLIC_KEY') {
        newLines.push(`${match[1]}=${anchorPubKey}`);
      } else {
        newLines.push(line);
      }
    } else {
      newLines.push(line);
    }
  }

  for (const [key, val] of Object.entries(envVars)) {
    if (!existingKeys.has(key)) {
      newLines.push(`${key}=${val}`);
    }
  }

  fs.writeFileSync(envPath, newLines.join('\n') + '\n', 'utf8');
  console.log(`   Configured ${envPath}`);

  console.log('\n======================================================');
  console.log('✅ ProofChain Environment Setup Complete!');
  console.log('======================================================');
  console.log(`🛡️ Pinned Anchor Key:  ${anchorPubKey}`);
  console.log(`🔑 Issuer Access Code: ${registryApiToken}`);
  console.log('======================================================\n');
}

main().catch((err) => {
  console.error('Setup failed:', err);
  process.exit(1);
});
